use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use protocol::terminals::{EndedEvent, FrameEvent};
use protocol::{Connection, Event, Frame};
use ts_rs::{Config, TS, TypeVisitor};

use super::{Handler, ROUTER};

pub struct Types {
    cfg: Config,
    declared: BTreeMap<String, String>,
}

pub struct Entry {
    params: String,
    result: String,
}

impl TypeVisitor for Types {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if T::output_path().is_some() {
            let name = T::ident(&self.cfg);
            if self.declared.contains_key(&name) {
                return;
            }

            self.declared.insert(name, T::decl(&self.cfg));
        }

        T::visit_dependencies(self);
        T::visit_generics(self);
    }
}

pub fn entry<M: Handler>(types: &mut Types) -> Entry {
    types.visit::<M::Params>();
    types.visit::<M::Result>();

    Entry {
        params: M::Params::name(&types.cfg),
        result: M::Result::name(&types.cfg),
    }
}

fn event<E: Event>(types: &mut Types) -> String {
    types.visit::<E::Params>();

    format!("  {:?}: {};\n", E::NAME, E::Params::name(&types.cfg))
}

#[test]
fn export_protocol() {
    let mut types = Types {
        cfg: Config::default(),
        declared: BTreeMap::new(),
    };
    types.visit::<Connection>();
    types.visit::<Frame>();

    let mut methods = String::new();
    for (name, route) in &ROUTER.routes {
        let entry = (route.export)(&mut types);
        writeln!(
            methods,
            "  {name:?}: {{ params: {}; result: {} }};",
            entry.params, entry.result
        )
        .unwrap();
    }
    let events = event::<FrameEvent>(&mut types) + &event::<EndedEvent>(&mut types);

    let mut file = String::from("// Generated by crates/host. Do not edit.\n\n");
    for decl in types.declared.values() {
        writeln!(file, "export {decl}\n").unwrap();
    }
    write!(
        file,
        "export type Methods = {{\n{methods}}};\n\nexport type Events = {{\n{events}}};\n\nexport const offline = {};\n",
        protocol::rpc::OFFLINE
    )
    .unwrap();

    let path =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../apps/desktop/src/generated/protocol.ts");
    std::fs::write(path, file).unwrap();
}
