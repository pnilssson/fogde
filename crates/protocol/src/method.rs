use serde::Serialize;
use serde::de::DeserializeOwned;
use ts_rs::TS;

pub trait Method {
    const NAME: &'static str;
    type Params: DeserializeOwned + TS;
    type Result: Serialize + TS;
}

#[cfg(test)]
mod tests {
    use std::fmt::Write as _;
    use std::path::Path;

    use ts_rs::{Config, TS};

    use super::Method;
    use crate::github::{FinishSignIn, GetUser, StartSignIn, User};
    use crate::{Connection, Frame, Platform};

    fn named<T: TS>(file: &mut String, cfg: &Config) {
        writeln!(file, "export type {} = {};\n", T::name(cfg), T::inline(cfg)).unwrap();
    }

    fn entry<M: Method>(file: &mut String, cfg: &Config) {
        writeln!(
            file,
            "  {:?}: {{ params: {}; result: {} }};",
            M::NAME,
            M::Params::inline(cfg),
            M::Result::inline(cfg)
        )
        .unwrap();
    }

    #[test]
    fn export_methods() {
        let cfg = Config::default();
        let mut file = String::from("// Generated by crates/protocol. Do not edit.\n\n");
        named::<Connection>(&mut file, &cfg);
        named::<Frame>(&mut file, &cfg);
        named::<Platform>(&mut file, &cfg);
        named::<User>(&mut file, &cfg);
        file.push_str("export type Methods = {\n");
        entry::<GetUser>(&mut file, &cfg);
        entry::<StartSignIn>(&mut file, &cfg);
        entry::<FinishSignIn>(&mut file, &cfg);
        file.push_str("};\n");

        let path = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../apps/desktop/src/generated/protocol.ts");
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, file).unwrap();
    }
}
